import assert from 'node:assert/strict';
import {build} from 'esbuild';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const output=await build({entryPoints:['src/pages/receivablesV2/UnansweredUnits.tsx'],bundle:true,platform:'node',format:'cjs',jsx:'automatic',write:false,loader:{'.css':'empty'}});
const module={exports:{}};vm.runInNewContext(output.outputFiles[0].text,{module,exports:module.exports,require,Date,Intl,process,console,setTimeout,clearTimeout});
const {unansweredUnits}=module.exports;
const attempt=(result,at,collector='collector-1',date='2026-11-24')=>({result,at,collector,date});
const rows=['A10','A02','A03','B01','A04'].map(id=>({id,unitId:id,name:id}));
const records={A10:{contactOutcomes:[attempt('no_answer','2026-11-24T14:00Z'),attempt('no_answer','2026-11-24T15:00Z')]},A02:{contactOutcomes:[attempt('no_answer','2026-11-24T14:00Z')]},A03:{contactOutcomes:[attempt('no_answer','2026-11-24T14:00Z'),attempt('promise','2026-11-24T15:00Z')]},B01:{contactOutcomes:[attempt('no_answer','2026-11-24T14:00Z','collector-2')]},A04:{contactOutcomes:[attempt('no_answer','2026-11-23T14:00Z','collector-1','2026-11-23')]}};
const original=JSON.stringify(records);
const result=unansweredUnits(rows,records,'collector-1','2026-11-24');
assert.deepEqual(Array.from(result,x=>x.row.id),['A02','A10']);
assert.equal(result[1].attempts,2);
assert.equal(unansweredUnits(rows,records,'collector-2','2026-11-24').length,1);
assert.equal(unansweredUnits(rows,records,'collector-1','2026-11-25').length,0);
assert.equal(JSON.stringify(records),original);
console.log('PASS unanswered unit count, multiple attempts counted once, unit order, latest response removes pending, collector/day isolation and unchanged history.');

const formBuild=await build({entryPoints:['src/pages/receivablesV2/UnansweredActionForm.tsx'],bundle:true,platform:'node',format:'cjs',jsx:'automatic',write:false,packages:'external'});
const storage=new Map();
const formModule={exports:{}};
vm.runInNewContext(formBuild.outputFiles[0].text,{module:formModule,exports:formModule.exports,require,Date,Intl,console,localStorage:{getItem:key=>storage.get(key)??null,removeItem:key=>storage.delete(key),setItem:(key,value)=>storage.set(key,value)}});
const React=require('react');
const {renderToStaticMarkup}=require('react-dom/server');
const render=()=>renderToStaticMarkup(React.createElement(formModule.exports.UnansweredActionForm,{draftKey:'test',today:'2026-11-24',disabled:false,onSave:async()=>{}}));
storage.set('test:result',JSON.stringify('no_answer'));
const unansweredHtml=render();
assert.ok(unansweredHtml.includes('Guardar gestión'));
assert.ok(!unansweredHtml.includes('Monto acordado'));
assert.ok(!unansweredHtml.includes('<input'));
storage.set('test:result',JSON.stringify('promise'));
storage.set('test:amount',JSON.stringify('20'));
const promiseHtml=render();
assert.ok(promiseHtml.includes('Monto acordado'));
assert.ok(promiseHtml.includes('value="20"'));
assert.ok(promiseHtml.includes('Fecha'));
assert.ok(promiseHtml.includes('AM') && promiseHtml.includes('PM'));
console.log('PASS unanswered action form: no schedule or amount for no-answer; promise includes date, AM/PM and editable amount.');
