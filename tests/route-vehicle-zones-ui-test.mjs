import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const base = process.env.ROUTE_TEST_BASE ?? 'http://127.0.0.1:5174';
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  page.setDefaultTimeout(15000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
  for (const mode of ['', '&legacy', '&version=v2']) {
    await page.goto(`${base}/tests/fixtures/outside-route-cash.html?operator=delta1&zones${mode}`);
    await page.getByRole('button', { name: 'Trabajo (4)', exact: true }).waitFor();
    const zones = page.getByRole('group', { name: 'Filtrar por zona', exact: true });
    await zones.getByRole('button', { name: 'Centro (2)', exact: true }).waitFor();
    assert.deepEqual(await zones.getByRole('button').allTextContents(), ['Todas (4)', 'Centro (2)', 'Chorrillo (1)', 'Sin zona (1)']);
    await zones.getByRole('button', { name: 'Centro (2)', exact: true }).click();
    assert.equal(await page.locator('.route-collection-card').count(), 2, 'Same zone groups own units across PTY/WC routes.');
    await zones.getByRole('button', { name: 'Sin zona (1)', exact: true }).click();
    assert.equal(await page.locator('.route-collection-card').count(), 1);
    await zones.getByRole('button', { name: 'Todas (4)', exact: true }).click();
    const card = page.getByRole('article', { name: 'A10 · Pedro González', exact: true });
    await card.getByRole('button', { name: 'Cambiar ruta de A10', exact: true }).click();
    await card.getByRole('group', { name: 'Rutas disponibles para A10', exact: true }).getByRole('button', { name: 'CL', exact: true }).click();
    await card.getByRole('button', { name: 'Cambiar ruta de A10', exact: true }).waitFor();
    await page.getByRole('status').filter({ hasText: 'A10 cambió a CL.' }).waitFor();
    assert.equal(await card.locator('.route-collection-route-options').count(), 0, 'Route options close after choosing.');
    await card.getByLabel('Zona de A10', { exact: true }).fill('Chorrillo');
    await card.getByLabel('Zona de A10', { exact: true }).press('Enter');
    await zones.getByRole('button', { name: 'Chorrillo (2)', exact: true }).waitFor();
    await zones.getByRole('button', { name: 'Chorrillo (2)', exact: true }).click();
    assert.equal(await page.locator('.route-collection-card').count(), 2);
    assert.equal(await page.evaluate(() => window.__vehicleRequests.length), 0, 'Vehicle queries run only on opening details.');
    await card.locator('.route-collection-details > summary').click();
    const vehicle = card.getByRole('region', { name: 'Datos del auto', exact: true });
    await vehicle.getByText('Toyota Yaris', { exact: true }).waitFor();
    assert.equal(await vehicle.getByText('AB1234', { exact: true }).count(), 1);
    assert.equal(await vehicle.getByText('Blanco', { exact: true }).count(), 1);
    assert.equal(await vehicle.getByRole('textbox').count(), 0);
    const request = await page.evaluate(() => window.__vehicleRequests[0]);
    assert.equal(request.p_client_id, 'active');
    assert.equal(request.p_version, mode.includes('v2') ? 'v2' : 'legacy');
    await card.locator('.route-collection-details > summary').click();
    await page.evaluate(() => { window.__vehicleDetails = { plate:'NEW-01', color:null, brandModel:'Toyota Yaris' }; });
    await card.locator('.route-collection-details > summary').click();
    await vehicle.getByText('NEW-01', { exact: true }).waitFor();
    assert.equal(await vehicle.getByText('Sin registrar', { exact: true }).count(), 1);
    await card.locator('.route-collection-details > summary').click();
    await page.evaluate(() => { window.__failVehicle = true; });
    await card.locator('.route-collection-details > summary').click();
    await vehicle.getByRole('alert').waitFor();
    assert.equal(await vehicle.getByText('Sin registrar', { exact: true }).count(), 0, 'Errors are not missing vehicle data.');
    await page.evaluate(() => { window.__failVehicle = false; });
    await vehicle.getByRole('button', { name: 'Reintentar', exact: true }).click();
    await vehicle.getByText('NEW-01', { exact: true }).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    const time = card.locator('.route-collection-route-time--progressive');
    const duration = await time.locator('strong').boundingBox();
    const status = await time.locator('em').boundingBox();
    assert.ok(duration.x + duration.width <= status.x || duration.y + duration.height <= status.y, 'Duration and urgency do not overlap.');
    await page.setViewportSize({ width: 1280, height: 900 });
  }
  assert.deepEqual(errors, []);
  console.log('Route UI: zone counts across routes, own Delta scope, no-zone filter, route change, zone edits, vehicle lazy load/refresh/retry/V2 and mobile layout OK');
} finally { await browser.close(); }
